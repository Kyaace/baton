"""Pytest configuration and lifecycle hooks for Baton test suite."""

from __future__ import annotations

import shutil
from pathlib import Path
import pytest


def move_test_chat_sessions() -> int:
    """
    Moves test chat session logs from baton/logs to baton/logs/test.
    Any chat session log that does not contain a '[USER]' entry (or that contains
    automated test payload markers like 'Spencer (1971)') is classified as a test session.
    """
    logs_dir = Path("baton/logs")
    if not logs_dir.exists():
        return 0

    test_subfolder = logs_dir / "test"
    test_subfolder.mkdir(parents=True, exist_ok=True)

    moved_count = 0
    for log_path in sorted(logs_dir.glob("chat_session_*.log")):
        try:
            content = log_path.read_text(encoding="utf-8", errors="replace")
            # If no [USER] entry, or generated by the automated test mock:
            if "[USER]" not in content or "Spencer (1971)" in content:
                dest = test_subfolder / log_path.name
                shutil.move(str(log_path), str(dest))
                moved_count += 1
        except Exception:
            pass

    # Ensure chat_latest.log points to the newest actual user chat session
    latest_log = logs_dir / "chat_latest.log"
    if latest_log.exists():
        try:
            latest_content = latest_log.read_text(encoding="utf-8", errors="replace")
            if "[USER]" not in latest_content or "Spencer (1971)" in latest_content:
                shutil.move(str(latest_log), str(test_subfolder / "chat_latest.log"))

                user_logs = sorted(
                    [
                        p for p in logs_dir.glob("chat_session_*.log")
                        if "[USER]" in p.read_text(encoding="utf-8", errors="replace")
                        and "Spencer (1971)" not in p.read_text(encoding="utf-8", errors="replace")
                    ],
                    key=lambda p: p.stat().st_mtime,
                    reverse=True,
                )
                if user_logs:
                    shutil.copy2(str(user_logs[0]), str(latest_log))
        except Exception:
            pass

    return moved_count


def pytest_sessionfinish(session, exitstatus):
    """Pytest hook that runs automatically after all test execution finishes."""
    move_test_chat_sessions()
